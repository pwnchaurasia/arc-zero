#!/usr/bin/env python3
"""Generate the fixed-point trig table used by the Brick Blast physics.

The table is generated ONCE and committed. It must never be computed at build
or run time: libm `sin/cos` can differ by one ulp between platforms, which
would let the browser and the server disagree about a bounce.

Usage: python3 tools/gen_trig_table.py > crates/arc-engine/src/brick_blast/trig_table.rs
"""

import math

SCALE = 1 << 16
STEPS = 1800  # tenths of a degree, 0.0° .. 180.0°


def main() -> None:
    cos = [round(math.cos(math.radians(i / 10)) * SCALE) for i in range(STEPS + 1)]
    sin = [round(math.sin(math.radians(i / 10)) * SCALE) for i in range(STEPS + 1)]
    print("// @generated by tools/gen_trig_table.py. DO NOT EDIT.")
    print("// cos/sin of i/10 degrees for i in 0..=1800, scaled by 2^16.")
    print()
    print(f"pub const TRIG_SCALE: i64 = {SCALE};")
    print()
    for name, values in (("COS", cos), ("SIN", sin)):
        print("#[rustfmt::skip]")
        print(f"pub static {name}: [i32; {STEPS + 1}] = [")
        for i in range(0, len(values), 12):
            print("    " + ", ".join(str(v) for v in values[i : i + 12]) + ",")
        print("];")
        print()


if __name__ == "__main__":
    main()
